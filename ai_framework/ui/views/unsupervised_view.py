def _render_eda(datos: pd.DataFrame) -> None:
    """Display exploratory charts generated by EDA."""
    _dataset_module_summary(datos)
    eda = EDA(dataframe=datos)
    (
        resumen,
        histogramas,
        boxplots,
        dispersion,
        correlacion,
        outliers,
        frecuencias,
    ) = st.tabs(
        [
            t("eda_tab_resumen", "Resumen"),
            t("eda_tab_histogramas", "Histogramas"),
            t("eda_tab_boxplots", "Boxplots"),
            t("eda_tab_dispersion", "Dispersión"),
            t("eda_tab_correlacion", "Correlación"),
            t("eda_tab_outliers", "Outliers"),
            t("eda_tab_frecuencias", "Frecuencias"),
        ]
    )

    with resumen:
        col_rename = {
            "mediana": t("eda_col_mediana", "mediana"),
            "nulos": t("eda_col_nulos", "nulos"),
            "porcentaje_nulos": t("eda_col_porcentaje_nulos", "porcentaje_nulos"),
        }
        for nombre, tabla in eda.distribucion_variables().items():
            if not tabla.empty:
                nombre_trad = (
                    t("eda_vars_numericas", t("eda_vars_numericas", "Variables numéricas"))
                    if nombre == "numericas"
                    else t("eda_vars_categoricas", "Variables categóricas")
                )
                st.markdown(f"**{nombre_trad}**")
                tabla_mostrada = tabla.rename(columns=col_rename)
                st.dataframe(tabla_mostrada, width="stretch")

    numericas = _numeric_columns(datos)
    with histogramas:
        seleccion = st.multiselect(
            t("eda_vars_numericas", "Variables numéricas"),
            numericas,
            default=numericas[:3],
            key="eda_histogramas",
        )
        if seleccion:
            figura = eda.histogramas(seleccion, mostrar=False)
            _display_figure(figura)

    with boxplots:
        seleccion = st.multiselect(
            t("eda_vars_numericas", "Variables numéricas"),
            numericas,
            default=numericas[:3],
            key="eda_boxplots",
        )
        if seleccion:
            figura = eda.boxplots(seleccion, mostrar=False)
            _display_figure(figura)

    with dispersion:
        seleccion = st.multiselect(
            t("eda_vars_numericas", "Variables numéricas"),
            numericas,
            default=numericas[:4],
            key="eda_dispersion",
        )
        if len(seleccion) >= 2 and st.button(t("eda_generar_dispersion", "Generar dispersión")):
            grafico = eda.scatterplots(seleccion, mostrar=False)
            _display_figure(grafico)

    with correlacion:
        seleccion = st.multiselect(
            t("eda_vars_numericas", "Variables numéricas"),
            numericas,
            default=numericas[:8],
            key="eda_correlacion",
        )
        metodo = st.selectbox(
            t("eda_metodo", "Método"), ["pearson", "spearman", "kendall"], key="eda_metodo"
        )
        if len(seleccion) >= 2:
            figura, matriz = eda.mapa_calor(
                seleccion, metodo=metodo, mostrar=False
            )
            _display_figure(figura)
            st.dataframe(matriz, width="stretch")

    with outliers:
        factor = st.slider(t("eda_factor_iqr", "Factor IQR"), 1.0, 3.0, 1.5, 0.1)
        if numericas:
            resultado = eda.detectar_outliers(numericas, factor_iqr=factor)
            st.dataframe(resultado["resumen"], width="stretch")
            st.metric(
                t("eda_filas_outliers", "Filas con algún valor atípico"),
                len(resultado["filas_con_algun_outlier"]),
            )

    with frecuencias:
        seleccion = st.multiselect(
            t("eda_variables", "Variables"),
            datos.columns.tolist(),
            default=datos.columns.tolist()[:3],
            key="eda_frecuencias",
        )
        for columna, tabla in eda.frecuencias(seleccion).items():
            with st.expander(t("eda_frecuencias_de", f"Frecuencias de {columna}", columna=columna)):
                tabla_mostrada = tabla.rename(
                    columns={
                        "frecuencia": t("eda_col_frecuencia", "frecuencia"),
                        "porcentaje": t("eda_col_porcentaje", "porcentaje"),
                    }
                )
                st.dataframe(tabla_mostrada, width="stretch")


def _render_pca(datos: pd.DataFrame, configuracion: dict) -> None:
    """Execute and display principal component analysis."""
    st.markdown(f"### {t('acp_titulo', 'Análisis de componentes principales')}")
    if len(datos) < 2 or len(configuracion["features"]) < 2:
        st.warning(
            t("acp_adv_min", "Seleccione al menos dos variables y dos filas para ejecutar el ACP.")
        )
        return
    maximo = min(10, len(datos), max(2, len(configuracion["features"])))
    componentes = _select_integer(
        t("acp_componentes", "Componentes"), 2, maximo, 2, key="acp_componentes"
    )
    firma = _fingerprint(configuracion, componentes)
    if st.button(t("acp_ejecutar", "Ejecutar ACP"), type="primary"):
        try:
            resultado = run_pca(datos, configuracion, n_componentes=componentes)
            _save_result("resultado_acp", firma, resultado)
        except Exception as exc:
            st.error(f"No fue posible ejecutar el ACP: {exc}")

    resultado = _retrieve_result("resultado_acp", firma)
    if resultado is None:
        return
    df_var = pd.concat(
        [resultado.varianza_explicada, resultado.varianza_acumulada], axis=1
    )
    df_var.columns = [
        t("acp_var_explicada", "Varianza explicada (%)"),
        t("acp_var_acumulada", "Varianza acumulada (%)"),
    ]
    st.dataframe(df_var, width="stretch")
    _display_figure(UnsupervisedVisualizer.varianza_acp(resultado))
    plano, circulo, sobreposicion = st.tabs(
        [t("acp_tab_plano", "Plano principal"), t("acp_tab_circulo", "Círculo de correlación"), t("acp_tab_sobreposicion", "Sobreposición")]
    )
    with plano:
        _display_figure(UnsupervisedVisualizer.plano_acp(resultado))
    with circulo:
        _display_figure(
            UnsupervisedVisualizer.circulo_correlacion(resultado)
        )
    with sobreposicion:
        _display_figure(UnsupervisedVisualizer.sobreposicion_acp(resultado))


def _render_partitional(
    datos: pd.DataFrame, configuracion: dict, algoritmo: str
) -> None:
    """Render a partitional clustering technique with common results flow."""
    st.markdown(f"### {algoritmo}")
    if len(datos) < 3 or not configuracion["features"]:
        st.warning(t("cluster_adv_min", "Se requieren variables y al menos tres filas."))
        return
    limite = min(12, len(datos) - 1)
    clusters = _select_integer(
        t("cluster_num_clusters", "Número de clusters"), 2, limite, 3, key=f"{algoritmo.lower()}_clusters"
    )
    firma = _fingerprint(configuracion, algoritmo, clusters)
    clave_resultado = f"resultado_{algoritmo.lower().replace('-', '_')}"
    if st.button(t("cluster_ejecutar", f"Ejecutar {algoritmo}", algoritmo=algoritmo), type="primary"):
        try:
            if algoritmo == "K-Means":
                resultado = run_kmeans(datos, configuracion, clusters)
            else:
                resultado = run_kmedoids(datos, configuracion, clusters)
            _save_result(clave_resultado, firma, resultado)
        except Exception as exc:
            st.error(f"No fue posible agrupar el dataset: {exc}")

    resultado = _retrieve_result(clave_resultado, firma)
    if resultado is not None:
        c1, c2 = st.columns(2)
        c1.metric(
            t("cluster_silhouette", "Silhouette"),
            f"{resultado.silhouette:.4f}"
            if resultado.silhouette is not None
            else t("no_disponible", "No disponible"),
        )
        c2.metric(
            t("cluster_inercia", "Inercia"),
            f"{resultado.inercia:.4f}"
            if resultado.inercia is not None
            else t("no_aplica", "No aplica"),
        )
        _display_figure(UnsupervisedVisualizer.clusters(resultado))
        _display_figure(UnsupervisedVisualizer.perfiles_cluster(resultado))
        salida = datos.loc[resultado.etiquetas.index].copy()
        salida["cluster"] = resultado.etiquetas
        st.download_button(
            t("cluster_descargar", "Descargar asignaciones"),
            salida.to_csv(index=False).encode("utf-8"),
            file_name="clusters.csv",
            mime="text/csv",
        )

    if algoritmo == "K-Means":
        firma_benchmark = _fingerprint(configuracion, "benchmark_kmeans")
        if st.button(t("cluster_evaluar_k", "Evaluar valores de k"), key="btn_evaluar_kmeans"):
            try:
                limite_k = min(10, len(datos) - 1)
                tabla = evaluate_kmeans_k(datos, configuracion, k_min=2, k_max=limite_k)
                _save_result("benchmark_kmeans", firma_benchmark, tabla)
            except Exception as exc:
                st.error(f"No fue posible evaluar k: {exc}")
        tabla = _retrieve_result("benchmark_kmeans", firma_benchmark)
        if tabla is not None:
            st.dataframe(tabla, width="stretch")
            _display_figure(
                UnsupervisedVisualizer.curva_evaluacion(tabla, "K-Means")
            )

    if algoritmo == "K-Means":
        with st.expander(t("cluster_proyecciones", "Proyecciones para visualizar los clusters")):
            etiquetas = (
                resultado.etiquetas if resultado is not None else None
            )
            tab_tsne, tab_umap = st.tabs(["t-SNE", "UMAP"])
            with tab_tsne:
                _render_tsne(
                    datos, configuracion, etiquetas=etiquetas, firma_cluster=firma
                )
            with tab_umap:
                _render_umap(
                    datos, configuracion, etiquetas=etiquetas, firma_cluster=firma
                )


def _render_hac(datos: pd.DataFrame, configuracion: dict) -> None:
    """Execute hierarchical clustering and display dendrogram."""
    st.markdown(f"### {t('hac_titulo', 'Clustering jerárquico aglomerativo')}")
    if len(datos) < 3 or not configuracion["features"]:
        st.warning(t("cluster_adv_min", "Se requieren variables y al menos tres filas."))
        return
    metodo = st.selectbox(
        t("hac_vinculacion", "Vinculación"), ["ward", "average", "complete", "single"]
    )
    limite = min(12, len(datos) - 1)
    clusters = _select_integer(
        t("cluster_num_clusters", "Número de clusters"), 2, limite, 3, key="hac_clusters"
    )
    filas_hac = min(configuracion["filas"], 800)
    firma = _fingerprint(configuracion, metodo, clusters, filas_hac)
    if st.button(t("hac_ejecutar", "Ejecutar HAC"), type="primary"):
        try:
            resultado = run_hac(
                datos,
                configuracion,
                clusters=clusters,
                metodo=metodo,
                filas_hac=filas_hac,
            )
            _save_result("resultado_hac", firma, resultado)
        except Exception as exc:
            st.error(f"No fue posible ejecutar HAC: {exc}")

    resultado = _retrieve_result("resultado_hac", firma)
    if resultado is not None:
        st.metric(
            t("cluster_silhouette", "Silhouette"),
            f"{resultado.silhouette:.4f}"
            if resultado.silhouette is not None
            else t("no_disponible", "No disponible"),
        )
        _display_figure(UnsupervisedVisualizer.dendrograma(resultado))
        _display_figure(UnsupervisedVisualizer.clusters(resultado))
        _display_figure(UnsupervisedVisualizer.perfiles_cluster(resultado))

    firma_benchmark = _fingerprint(configuracion, "benchmark_hac", filas_hac)
    if st.button(t("hac_comparar", "Comparar métodos HAC"), key="btn_comparar_hac"):
        try:
            limite_k = min(8, len(datos) - 1)
            tabla = compare_hac_methods(
                datos, configuracion, filas_hac=filas_hac, k_min=2, k_max=limite_k
            )
            _save_result("benchmark_hac", firma_benchmark, tabla)
        except Exception as exc:
            st.error(f"No fue posible comparar HAC: {exc}")

    tabla = _retrieve_result("benchmark_hac", firma_benchmark)
    if tabla is not None:
        st.dataframe(tabla, width="stretch")
        _display_figure(UnsupervisedVisualizer.curva_evaluacion(tabla, "HAC"))


def _render_tsne(
    datos: pd.DataFrame,
    configuracion: dict,
    *,
    etiquetas=None,
    firma_cluster=None,
) -> None:
    """Execute t-SNE on demand to contextualize K-Means solution."""
    st.markdown(f"### {t('tsne_titulo', 'Proyección t-SNE')}")
    filas = min(configuracion["filas"], 2000)
    if filas < 3 or not configuracion["features"]:
        st.warning(t("tsne_adv_min", "t-SNE requiere variables y al menos tres filas."))
        return
    max_perplexity = min(50, filas - 1)
    perplexity = _select_integer(
        "Perplexity", 2, max_perplexity, 30, key="tsne_perplexity"
    )
    iteraciones = st.slider(t("tsne_iteraciones", "Iteraciones"), 250, 2000, 1000, 250, key="tsne_iteraciones")
    firma = _fingerprint(configuracion, perplexity, iteraciones, filas, firma_cluster)
    clave = "resultado_kmeans_tsne"
    if st.button(t("tsne_ejecutar", "Ejecutar t-SNE"), type="primary"):
        try:
            resultado = run_tsne(
                datos,
                configuracion,
                filas=filas,
                perplexity=perplexity,
                iteraciones=iteraciones,
                etiquetas=etiquetas,
            )
            _save_result(clave, firma, resultado)
        except Exception as exc:
            st.error(f"No fue posible ejecutar t-SNE: {exc}")
    resultado = _retrieve_result(clave, firma)
    if resultado is not None:
        grupos = (
            etiquetas.reindex(resultado.coordenadas.index)
            if etiquetas is not None
            else None
        )
        _display_figure(
            UnsupervisedVisualizer.proyeccion(resultado, grupos)
        )
        st.dataframe(resultado.coordenadas, width="stretch")


def _render_umap(
    datos: pd.DataFrame,
    configuracion: dict,
    *,
    etiquetas=None,
    firma_cluster=None,
) -> None:
    """Execute UMAP on demand to contextualize K-Means solution."""
    st.markdown(f"### {t('umap_titulo', 'Proyección UMAP')}")
    filas = min(configuracion["filas"], 3000)
    if filas < 3 or not configuracion["features"]:
        st.warning(t("umap_adv_min", "UMAP requiere variables y al menos tres filas."))
        return
    max_vecinos = min(100, filas - 1)
    vecinos = _select_integer(
        t("umap_vecinos", "Vecinos"), 2, max_vecinos, 15, key="umap_vecinos"
    )
    distancia = st.slider(t("umap_distancia", "Distancia mínima"), 0.0, 0.99, 0.1, 0.05, key="umap_distancia")
    firma = _fingerprint(configuracion, vecinos, distancia, filas, firma_cluster)
    clave = "resultado_kmeans_umap"
    if st.button(t("umap_ejecutar", "Ejecutar UMAP"), type="primary"):
        try:
            resultado = run_umap(
                datos,
                configuracion,
                filas=filas,
                vecinos=vecinos,
                distancia=distancia,
                etiquetas=etiquetas,
            )
            _save_result(clave, firma, resultado)
        except DependenciaOpcionalError as exc:
            st.warning(str(exc))
        except Exception as exc:
            st.error(f"No fue posible ejecutar UMAP: {exc}")
    resultado = _retrieve_result(clave, firma)
    if resultado is not None:
        grupos = (
            etiquetas.reindex(resultado.coordenadas.index)
            if etiquetas is not None
            else None
        )
        _display_figure(
            UnsupervisedVisualizer.proyeccion(resultado, grupos)
        )
        st.dataframe(resultado.coordenadas, width="stretch")

